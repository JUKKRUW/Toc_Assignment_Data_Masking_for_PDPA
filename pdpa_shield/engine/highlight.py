"""Regex syntax highlighter — ระบายสี regex บนหน้า Rules (เขียนด้วย re เอง)   Owner: M07

หน้าที่: รับ regex ของแต่ละกฎ (เป็นข้อความ) แล้วหั่นเป็นชิ้นๆ (token) พร้อมบอกว่าแต่ละชิ้นเป็นชนิดอะไร
หน้าเว็บ (M10) จะเอาชนิดไปเลือกสี เช่น group สีม่วง ตัวนับซ้ำสีส้ม

ผลลัพธ์เป็นรายการ [ชนิด, ข้อความ] เช่น
    highlight_pattern(r"(?P<last4>\\d{4})")
    -> [["named", "(?P<last4>"], ["escape", "\\d"], ["quant", "{4}"], ["paren", ")"]]

ชนิดที่ต้องรองรับ
    comment  คอมเมนต์ "# ..." จนจบบรรทัด (ใน re.VERBOSE)
    look     (?=  (?!  (?<=  (?<!        lookahead / lookbehind
    backref  (?P=name)                   อ้างกลับ group เดิม
    named    (?P<name>                   group ที่มีชื่อ
    noncap   (?:                         group ที่ไม่เก็บค่า
    paren    ( หรือ )                    วงเล็บธรรมดา
    cls      [...]                       ชุดตัวอักษร (รองรับ \\] ข้างใน)
    quant    * + ? (และแบบ lazy เช่น *?) และ {n} {n,} {n,m}
    escape   \\d \\s \\. ...
    alt      |                           "หรือ"
    space    ช่องว่าง / ขึ้นบรรทัดใหม่
    lit      ตัวอักษรอื่นๆ
เอาข้อความทุกชิ้นมาต่อกัน ต้องได้ regex ต้นฉบับเป๊ะ

ไฟล์ทดสอบ: tests/engine/test_highlight.py
"""
from __future__ import annotations

import re

# regex ที่ใช้อ่าน regex :)
# แต่ละบรรทัดคือชนิด token 1 ชนิด ใช้ "|" (หรือ) ต่อกัน และตั้งชื่อ group ตามชนิด
# ลำดับสำคัญมาก: Python ลองจากบนลงล่าง ตัวที่เจาะจงกว่าต้องมาก่อน
#   เช่น "(?P<" ต้องมาก่อน "(" ไม่อย่างนั้นวงเล็บจะถูกจับเป็น paren ธรรมดาไปก่อน
# ข้อควรระวัง: ห้ามจบคอมเมนต์ในโหมด VERBOSE ด้วย backslash
#   เพราะ re จะอ่าน backslash + ขึ้นบรรทัดใหม่ เป็นตัวเดียวกัน แล้วกลืนบรรทัดถัดไปหายทั้งบรรทัด
_TOKEN_RE = re.compile(
    r"""
      (?P<comment>\#[^\n]*)                 # คอมเมนต์: # ตามด้วยอะไรก็ได้จนจบบรรทัด
    | (?P<look>\(\?<?[=!])                  # (?=  (?!  (?<=  (?<!   — < มีหรือไม่มีก็ได้
    | (?P<backref>\(\?P=\w+\))              # (?P=ชื่อ)
    | (?P<named>\(\?P<\w+>)                 # (?P<ชื่อ>
    | (?P<noncap>\(\?:)                     # (?:
    | (?P<paren>[()])                       # ( หรือ ) ที่เหลือ
    | (?P<cls>\[(?:\\.|[^\]\\])*\])         # [ ... ]  ข้างในเป็นตัวที่ escape แล้ว หรือตัวที่ไม่ใช่ ] และไม่ใช่ backslash
    | (?P<quant>[*+?]\??|\{\d+(?:,\d*)?\})  # * + ? (ตามด้วย ? = lazy) หรือ {n} {n,} {n,m}
    | (?P<escape>\\.)                       # backslash ตามด้วยตัวอะไรก็ได้ 1 ตัว เช่น \d \s \. (escape)
    | (?P<alt>\|)                           # |
    | (?P<space>\s+)                        # ช่องว่างติดกัน
    | (?P<lit>[^\s\\()\[\]*+?{}|\#]+|.)     # ตัวอักษรธรรมดาติดกัน หรือตัวอะไรก็ได้ 1 ตัวที่ไม่เข้าพวกไหน (กันหลุด)
    """,
    re.VERBOSE | re.DOTALL,                 # VERBOSE = เขียนหลายบรรทัด+คอมเมนต์ได้, DOTALL = . จับ \n ด้วย
)


def highlight_pattern(pattern: str) -> list[list[str]]:
    """หั่น regex เป็นรายการ [ชนิด, ข้อความ]"""
    # finditer ไล่จับ token ต่อกันไปจนจบข้อความ
    # m.lastgroup = ชื่อ group ที่จับได้ = ชนิดของ token,  m.group() = ข้อความของ token
    return [[m.lastgroup, m.group()] for m in _TOKEN_RE.finditer(pattern)]
