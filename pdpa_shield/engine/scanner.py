"""Scanner — ตัวสแกนและรวมผลของทุกกฎ (หัวใจของ masking engine)       Owner: M07

หน้าที่: รับข้อความ log + รายการกฎ แล้วหาว่าตรงไหนเป็นข้อมูลส่วนบุคคล
จากนั้นตัดข้อความออกเป็นชิ้นๆ (Parts) ส่งให้ API และหน้าเว็บ

ขั้นตอน (ต้องทำแบบนี้เป๊ะ เพราะหน้าเว็บอาศัยผลลัพธ์รูปแบบนี้)
    1. ไล่กฎทีละตัวตามลำดับความสำคัญ (ลำดับใน registry.RULES) เฉพาะกฎที่เปิดอยู่
         หาทุกจุดที่ regex ของกฎนั้นจับได้
             ถ้าตำแหน่งนั้น "ทับ" กับจุดที่รับไว้แล้ว -> ข้าม (กฎที่สำคัญกว่าได้ไปแล้ว)
             ถ้าไม่ทับ -> รับไว้
    2. เรียงจุดที่รับไว้ตามตำแหน่งในข้อความ (ซ้ายไปขวา)
    3. ตัดข้อความเป็นชิ้น สลับกันระหว่าง
           {"kind": "text"}  ข้อความธรรมดา
           {"kind": "pii"}   ข้อมูลส่วนบุคคล (มีทั้งของเดิมและของที่เซ็นเซอร์แล้ว)
       โดยเอาของเดิมทุกชิ้นมาต่อกัน ต้องได้ข้อความเดิมเป๊ะ (ไม่หาย ไม่ซ้ำ)

ตัวอย่าง
    ข้อความ: "tel 093-245-7894 ok"
    ผลลัพธ์: [ {"kind": "text", "text": "tel "},
              {"kind": "pii",  "rule": "phone", "original": "093-245-7894", "masked": "XXX-XXX-7894", ...},
              {"kind": "text", "text": " ok"} ]

กฎที่ pattern เป็น None (เพื่อนยังเขียนไม่เสร็จ) ต้องข้ามไปเฉยๆ ห้ามพัง

เรื่องความเร็ว (งาน benchmark ของ M07: log 10,000 บรรทัดต้องเสร็จใน 2 วินาที)
    วิธีตรงไปตรงมาคือเอาจุดใหม่ไปเทียบกับ "ทุกจุด" ที่รับไว้แล้ว
        log 10,000 บรรทัด เจอประมาณ 20,000 จุด -> เทียบกันประมาณ 200 ล้านครั้ง -> ช้า (~10 วินาที)
    ไฟล์นี้จึงเก็บจุดที่รับไว้ให้ "เรียงตามตำแหน่งเริ่ม" เสมอ
    แล้วใช้ bisect (ค้นหาแบบแบ่งครึ่ง / binary search) หาเพื่อนบ้านด้านซ้ายที่ใกล้ที่สุด
    เทียบแค่ตัวเดียวก็รู้ว่าทับหรือไม่ -> เหลือไม่ถึง 1 วินาที
    (bisect เป็นแค่การค้นหาในรายการ ส่วนการจับข้อมูลยังใช้ re ของ Python ล้วนๆ ตามโจทย์)

    ทำไมพอเทียบแค่กับ "กฎที่สำคัญกว่า":
        finditer คืนผลที่ไม่ทับกันเองอยู่แล้ว จุดของกฎเดียวกันจึงไม่มีทางทับกันเอง

ไฟล์ทดสอบ: tests/engine/test_scanner.py (ใช้กฎปลอม ไม่ต้องรอกฎของเพื่อน)
"""
from __future__ import annotations

import re
from bisect import bisect_left
from typing import Iterable, Optional

from pdpa_shield.engine.types import Part, Rule


def scan(text: str, rules: list[Rule], enabled: Optional[Iterable[str]] = None) -> list[Part]:
    """คืนรายการ Parts ของข้อความ `text`   (enabled=None แปลว่าเปิดทุกกฎ)"""
    # กฎที่ผู้ใช้เปิดไว้ (หน้าเว็บมีปุ่มเปิด/ปิดแต่ละกฎ)
    keys = set(enabled) if enabled is not None else {r.key for r in rules}

    # จุดที่รับไว้แล้ว 1 จุด = (ตำแหน่งเริ่ม, ตำแหน่งจบ, กฎที่จับได้, ผลการจับของ regex)
    # รายการนี้เรียงจากซ้ายไปขวาเสมอ (ตามตำแหน่งเริ่ม แล้วตามตำแหน่งจบ)
    accepted: list[tuple[int, int, Rule, re.Match]] = []

    # ---------- ขั้นที่ 1 + 2: ไล่กฎตามลำดับความสำคัญ ----------
    for rule in rules:
        if rule.key not in keys or rule.pattern is None:
            continue                                   # กฎถูกปิด หรือยังไม่มี regex -> ข้าม ไม่พัง

        # ตำแหน่งเริ่ม/จบ ของจุดที่กฎที่สำคัญกว่ารับไว้แล้ว (เรียงจากซ้ายไปขวา)
        # จุดที่รับไว้ไม่มีทางทับกันเอง ดังนั้นเมื่อ starts เรียงแล้ว ends ก็เรียงไปด้วย
        starts = [a[0] for a in accepted]
        ends = [a[1] for a in accepted]

        new: list[tuple[int, int, Rule, re.Match]] = []
        for m in rule.pattern.finditer(text):          # finditer = หาทุกจุดในข้อความที่ตรงกับ regex (ซ้ายไปขวา)
            # ตำแหน่งของ "ส่วนที่จะเซ็นเซอร์"
            #   target = 0        -> ทั้งก้อนที่ regex จับได้
            #   target = "house"  -> เฉพาะ group ชื่อ house (เช่น ที่อยู่ เซ็นเซอร์แค่เลขที่บ้าน)
            s, e = m.span(rule.target)

            # เช็กว่าทับกับจุดของกฎที่สำคัญกว่าไหม
            #   i = จำนวนจุดที่ "เริ่มก่อนเราจบ" (หาด้วย binary search)
            #   จุดที่ i-1 คือตัวที่เริ่มหลังสุดในกลุ่มนั้น และจบช้าที่สุดด้วย
            #   ถ้ามันยังไม่จบตอนที่เราเริ่ม (ends > s) -> ทับกัน -> ข้าม เพราะกฎที่สำคัญกว่าได้ไปแล้ว
            #   ตัวอย่าง: รับ [5, 10) ไว้แล้ว  จุดใหม่ [8, 20)  -> 10 > 8  จริง  -> ทับ
            #                                  จุดใหม่ [10, 20) -> 10 > 10 ไม่จริง -> ไม่ทับ (แค่ติดกัน)
            i = bisect_left(starts, e)
            if i > 0 and ends[i - 1] > s:
                continue
            new.append((s, e, rule, m))                # ไม่ทับ -> รับไว้

        # รวมจุดของกฎนี้เข้ากับของเดิม แล้วเรียงตาม (ตำแหน่งเริ่ม, ตำแหน่งจบ)
        #   - ทั้งสองรายการเรียงอยู่แล้ว Python จึงรวมได้เร็วมาก
        #   - ถ้าเริ่มตรงกัน จุดที่ยาว 0 ตัวอักษรมาก่อน ไม่อย่างนั้นข้อความจะถูกพิมพ์ซ้ำ และ ends จะไม่เรียง
        #   - ถ้าตรงกันทั้งคู่ ของกฎที่สำคัญกว่าอยู่ก่อน (sorted ของ Python ไม่สลับลำดับของที่เท่ากัน)
        accepted = sorted(accepted + new, key=lambda a: (a[0], a[1]))

    # ---------- ขั้นที่ 3: ตัดข้อความเป็นชิ้น text / pii ----------
    parts: list[Part] = []
    pos = 0                                            # ตำแหน่งที่ตัดมาถึงแล้ว
    for s, e, rule, m in accepted:
        if pos < s:                                    # มีข้อความธรรมดาคั่นอยู่ก่อนข้อมูลส่วนบุคคล
            parts.append({"kind": "text", "text": text[pos:s]})
        parts.append({
            "kind": "pii",
            "rule": rule.key,                          # กฎไหนจับได้ เช่น "phone"
            "original": text[s:e],                     # ของเดิม ก่อนเซ็นเซอร์
            "masked": rule.replace(m),                 # ของใหม่ หลังเซ็นเซอร์ (ฟังก์ชัน mask ของเจ้าของกฎ)
            "match": m.group(0),                       # ข้อความทั้งก้อนที่ regex จับได้
            "groups": {k: v for k, v in m.groupdict().items() if v is not None},  # named group ที่จับได้
            "info": rule.info(m) if rule.info else None,  # ข้อมูลเสริมไว้โชว์ใน tooltip (เช่น Luhn ของบัตร)
        })
        pos = e
    if pos < len(text):                                # ข้อความที่เหลือหลังข้อมูลส่วนบุคคลตัวสุดท้าย
        parts.append({"kind": "text", "text": text[pos:]})
    return parts


def mask_text(text: str, rules: list[Rule], enabled: Optional[Iterable[str]] = None) -> str:
    """คืนข้อความที่เซ็นเซอร์แล้วทั้งหมด = เอาชิ้น text เดิม + ชิ้น pii ที่เซ็นเซอร์แล้ว มาต่อกัน"""
    return "".join(p["masked"] if p["kind"] == "pii" else p["text"] for p in scan(text, rules, enabled))
